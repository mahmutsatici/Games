let current: Lang = 'en';

export function setLang(l: string): void {
  const base = l.trim().toLowerCase().split(/[-_]/)[0];
  current = (LANGS as readonly string[]).includes(base) ? (base as Lang) : 'en';
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key): string {
  return DICT[current][key];
}
