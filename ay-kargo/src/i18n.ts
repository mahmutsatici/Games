export type Key = keyof typeof DICT;

const FALLBACK: Lang = 'en';

let current: Lang = FALLBACK;

function isLang(l: string): l is Lang {
  return (LANGS as readonly string[]).includes(l);
}

export function setLang(l: string): void {
  current = isLang(l) ? l : FALLBACK;
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key): string {
  return DICT[key][current] ?? DICT[key][FALLBACK];
}
